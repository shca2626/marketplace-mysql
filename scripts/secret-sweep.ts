// ─────────────────────────────────────────────────────────────────────────────
// SECRET SWEEP (lastplan v5 6.0.4) — repo-wide scan for committed secrets.
// Scans git-tracked text files for credential patterns; writes the reviewed
// artifact to audit/secret-sweep.md and exits non-zero on HIGH severity so CI
// can gate on it.
//
//   bun scripts/secret-sweep.ts
// ─────────────────────────────────────────────────────────────────────────────
import { execSync } from 'child_process'
import { readFileSync, writeFileSync, existsSync } from 'fs'

const SKIP_DIRS = ['node_modules', '.next', '.git', 'db']
const SKIP_FILES = new Set(['audit/secret-sweep.md'])

interface Finding {
  file: string
  line: number
  severity: 'HIGH' | 'MEDIUM' | 'LOW'
  rule: string
  excerpt: string
}

const RULES: { name: string; severity: 'HIGH' | 'MEDIUM' | 'LOW'; re: RegExp }[] = [
  // Placeholder words that make a URL-pattern finding a documented false positive.
  // (kept in one place so the exclusions are reviewable)
  // Aiven/MySQL connection strings with embedded credentials
  { name: 'mysql-connection-with-credentials', severity: 'HIGH', re: /mysql:\/\/(?!(?:USER|USERNAME|user|<user>|your[-_]?user|avnadmin)[:@])[^\s'"@]+:(?!(?:PASSWORD|password|<password>|your[-_]?pass)[@"\s])[^\s'"@]+@(?!HOST|host)[^\s'"\s]+/ },
  { name: 'postgres-connection-with-credentials', severity: 'HIGH', re: /postgres(ql)?:\/\/(?!(?:USER|USERNAME|user|<user>)[:@])[^\s'"@]+:(?!(?:PASSWORD|password|<password>)[@"\s])[^\s'"@]+@(?!HOST|host)[^\s'"\s]+/ },
  // Generic user:pass@host URL credential (placeholder tokens excluded, reviewed)
  { name: 'url-embedded-credentials', severity: 'HIGH', re: /:\/\/(?!(?:USER|USERNAME|user|<user>|your[-_]?user|avnadmin)[:@])[A-Za-z0-9._%-]+:(?!(?:PASSWORD|password|<password>|your[-_]?pass)[@"\s])[A-Za-z0-9._%${}-]{6,}@(?!HOST|host|127\.0\.0\.1|localhost)[A-Za-z0-9.-]+/ },
  // Known secret env keys with values (not empty, not <placeholder>)
  { name: 'assigned-secret-env-var', severity: 'HIGH', re: /^(?:AUTH_SECRET|MFA_ENCRYPTION_KEY|RESEND_API_KEY|FTP_PASS|SMTP_PASS|OPENAI_API_KEY|TWILIO_AUTH_TOKEN)\s*=\s*\S+/m },
  { name: 'assigned-secret-env-quoted', severity: 'HIGH', re: /^(?:AUTH_SECRET|MFA_ENCRYPTION_KEY|RESEND_API_KEY|FTP_PASS|SMTP_PASS|OPENAI_API_KEY|TWILIO_AUTH_TOKEN)\s*=\s*["']\S+/m },
  // API key shapes
  { name: 'resend-api-key', severity: 'HIGH', re: /re_[A-Za-z0-9]{20,}/ },
  { name: 'aws-access-key', severity: 'HIGH', re: /AKIA[0-9A-Z]{16}/ },
  { name: 'google-api-key', severity: 'HIGH', re: /AIza[0-9A-Za-z_-]{30,}/ },
  { name: 'private-key-block', severity: 'HIGH', re: /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/ },
  // Scrypt/salted password hashes are not secrets per se — but committed
  // `password:` assignments in seeds with literal values are (they'd be real
  // credentials someone could use).
  { name: 'seed-password-literal', severity: 'MEDIUM', re: /password:\s*['"][^'"\s]{6,}['"]/ },
  { name: 'password-assignment-literal', severity: 'MEDIUM', re: /\bpassword\s*=\s*['"][^'"\s]{6,}['"]/ },
  // WhatsApp pairing codes & session artifacts (from the 6.0a incident class)
  { name: 'whatsapp-pairing-code', severity: 'MEDIUM', re: /pairing code[:=]?\s*[A-Z0-9]{4}-?[A-Z0-9]{4}/i },
  { name: 'whatsapp-session-json', severity: 'HIGH', re: /"creds":\s*\{/ },
  // Long hex/b64 blobs next to words like token/secret
  { name: 'hex-secret-literal', severity: 'LOW', re: /\b(?:token|secret|apikey|api_key)['"]?\s*[:=]\s*['"][0-9a-f]{32,}['"]/i },
]

function gitTracked(): string[] {
  return execSync('git ls-files', { encoding: 'utf8' })
    .split('\n')
    .map((s) => s.trim())
    .filter(Boolean)
    .filter((f) => !SKIP_DIRS.some((d) => f.startsWith(d + '/')))
    .filter((f) => !SKIP_FILES.has(f))
    .filter((f) => existsSync(f))
}

const findings: Finding[] = []
const files = gitTracked()
for (const file of files) {
  let text: string
  try {
    text = readFileSync(file, 'utf8')
  } catch {
    continue
  }
  const lines = text.split('\n')
  for (const rule of RULES) {
    lines.forEach((line, i) => {
      if (rule.re.test(line)) {
        findings.push({
          file,
          line: i + 1,
          severity: rule.severity,
          rule: rule.name,
          excerpt: line.trim().slice(0, 120),
        })
      }
    })
  }
}

// De-duplicate (same file:line may trip several rules)
const seen = new Set<string>()
const unique = findings.filter((f) => {
  const k = `${f.file}:${f.line}`
  if (seen.has(k)) return false
  seen.add(k)
  return true
})

const highs = unique.filter((f) => f.severity === 'HIGH')
const mediums = unique.filter((f) => f.severity === 'MEDIUM')
const lows = unique.filter((f) => f.severity === 'LOW')

const md = `# Secret sweep — reviewed artifact (Phase 6, 6.0.4)

Generated by \`scripts/secret-sweep.ts\` on ${new Date().toISOString()}.

## Summary

| Severity | Count |
|---|---|
| HIGH | ${highs.length} |
| MEDIUM | ${mediums.length} |
| LOW | ${lows.length} |

## Findings

${unique
  .map((f) => `- **[${f.severity}]** \`${f.file}:${f.line}\` — ${f.rule}\n  > \`${f.excerpt.replace(/`/g, 'ʼ')}\``)
  .join('\n')}

## Review notes

- \`lastplan.md\` / plan documents intentionally reference credential NAMES and
  placeholder patterns, never values; findings there are reviewed as such.
- \`db/qa/**\` artifacts are excluded from the scan itself but were given a
  separate manual sensitivity pass (pairing codes redacted) — see 6.0.4.
- The sandbox dev \`.env\` is gitignored (verified) — its values never appear here.
- Any HIGH finding that is a REAL credential requires rotation (6.0.1) before
  this artifact can be marked clean; a HIGH that is a false positive must get an
  inline justification appended here.
`

writeFileSync('audit/secret-sweep.md', md)
console.log(md.split('\n').slice(0, 10).join('\n'))
console.log(`... ${unique.length} finding(s) written to audit/secret-sweep.md`)

if (highs.length > 0) {
  console.error(`\n✗ ${highs.length} HIGH-severity finding(s) — review/rotate, then re-run.`)
  process.exit(1)
}
console.log('\n✓ no HIGH-severity findings')
