// ─────────────────────────────────────────────────────────────────────────────
// ROUTE MATRIX GENERATOR (lastplan v5 6.9) — emits audit/route-matrix.md from
// the reviewed classification + the non-route entry-point register (6.1.4).
//
//   bun scripts/gen-route-matrix.ts
//
// The matrix is the reviewed artifact; check-guards.ts is the enforcement.
// ─────────────────────────────────────────────────────────────────────────────
import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'

const ROOT = process.cwd()

interface RouteClass {
  route: string
  bucket: string
  methods: string[]
  permissionKeys?: string[]
  moduleKeys?: string[]
  notes?: string
}

/** Non-route entry points (6.1.4 widened scope) — maintained by hand,
 *  reviewed with every change. Jobs run with system privileges; mini-service
 *  endpoints are network-reachable. */
const NON_ROUTE_ENTRY_POINTS: { name: string; kind: 'JOB' | 'MINI_SERVICE' | 'CRON'; env: string; authorization: string }[] = [
  { name: 'recurring-RFQ sweep (server module, scheduler)', kind: 'JOB', env: 'app runtime', authorization: 'System context — no user session; lease/idempotency rules in 7.5' },
  { name: 'expiry scans (certifications/accreditations)', kind: 'JOB', env: 'app runtime', authorization: 'System context — audit-logged writes only' },
  { name: 'digest jobs (notification digests)', kind: 'JOB', env: 'app runtime', authorization: 'System context — outbound email channel only' },
  { name: 'mini-services/whatsapp-service (port 3031)', kind: 'MINI_SERVICE', env: 'dev/staging (localhost-bound)', authorization: 'No auth surface beyond pairing + health; scheduled for classification if endpoints grow (see audit/admin-bypass-sweep.md allowlist)' },
  { name: 'cron webDevReview (dev sandbox)', kind: 'CRON', env: 'dev only', authorization: 'Dev-environment agent; documented in docs/environments.md' },
]

function main() {
  const classification: { routes: RouteClass[] } = JSON.parse(
    readFileSync(join(ROOT, 'audit/route-classification.json'), 'utf8')
  )
  const routes = [...classification.routes].sort((a, b) =>
    a.bucket === b.bucket ? a.route.localeCompare(b.route) : a.bucket.localeCompare(b.bucket)
  )

  const lines: string[] = []
  lines.push('# Route authorization matrix (Phase 6, 6.9 — generated artifact)')
  lines.push('')
  lines.push(`Generated by \`scripts/gen-route-matrix.ts\` on ${new Date().toISOString()} from the reviewed classification (\`audit/route-classification.json\`, enforced by \`scripts/check-guards.ts\`).`)
  lines.push('')
  lines.push(`Total route entry points: **${routes.length}** · non-route entry points: **${NON_ROUTE_ENTRY_POINTS.length}**`)
  lines.push('')

  let currentBucket = ''
  for (const r of routes) {
    if (r.bucket !== currentBucket) {
      currentBucket = r.bucket
      lines.push('')
      lines.push(`## ${currentBucket}`)
      lines.push('')
      lines.push('| Route | Methods | Permission keys | Module keys | Notes |')
      lines.push('|---|---|---|---|---|')
    }
    lines.push(
      `| \`${r.route}\` | ${r.methods.join(', ')} | ${(r.permissionKeys ?? []).map((k) => `\`${k}\``).join(', ') || '—'} | ${(r.moduleKeys ?? []).map((k) => `\`${k}\``).join(', ') || '—'} | ${(r.notes ?? '').replace(/\|/g, '\\|') || '—'} |`
    )
  }

  lines.push('')
  lines.push('## Non-route entry points (6.1.4 widened scope)')
  lines.push('')
  lines.push('| Entry point | Kind | Environment | Authorization model |')
  lines.push('|---|---|---|---|')
  for (const nr of NON_ROUTE_ENTRY_POINTS) {
    lines.push(`| ${nr.name} | ${nr.kind} | ${nr.env} | ${nr.authorization} |`)
  }
  lines.push('')

  writeFileSync(join(ROOT, 'audit/route-matrix.md'), lines.join('\n') + '\n')
  console.log(`✓ audit/route-matrix.md written — ${routes.length} routes + ${NON_ROUTE_ENTRY_POINTS.length} non-route entry points`)
}

main()
